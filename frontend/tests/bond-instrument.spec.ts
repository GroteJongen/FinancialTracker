import { expect, test } from './fixtures'

test('add instrument switches between listed assets and appropriate bond fields', async ({ page }) => {
  const account = await (await page.request.post('/api/bond-accounts', { data: { name: 'TEST wybór obligacji ' + Date.now(), kind: 'IKZE' } })).json()
  await page.goto('/')
  await page.locator('.operations-panel > summary').click()
  const section = page.getByRole('region', { name: 'Instrumenty', exact: true })
  await section.getByRole('button', { name: 'Dodaj instrument', exact: true }).click()
  await section.getByLabel('Nazwa instrumentu', { exact: true }).fill('TEST szkic ETF')
  const kind = section.getByLabel('Rodzaj aktywa', { exact: true })
  await kind.selectOption('BOND')
  await expect(section.getByLabel('Nazwa instrumentu', { exact: true })).toHaveCount(0)
  await expect(section.getByLabel('Ticker instrumentu', { exact: true })).toHaveCount(0)
  await expect(section.getByLabel('Giełda instrumentu (MIC)', { exact: true })).toHaveCount(0)
  await expect(section.getByRole('button', { name: 'Zapisz instrument', exact: true })).toHaveCount(0)
  const bonds = section.getByRole('region', { name: 'Obligacje skarbowe', exact: true })
  await bonds.getByLabel('Rachunek obligacji', { exact: true }).selectOption(account.id)
  await expect(bonds.getByLabel('Seria obligacji', { exact: true })).toBeVisible()
  await expect(bonds.getByLabel('Liczba obligacji', { exact: true })).toBeVisible()
  await expect(bonds.getByLabel('Cena jednej obligacji (PLN)', { exact: true })).toBeVisible()
  await bonds.getByLabel('Rodzaj obligacji', { exact: true }).selectOption('COI')
  await expect(bonds.getByLabel('Marża ponad inflację (%) — opcjonalnie', { exact: true })).toBeVisible()
  await bonds.getByLabel('Rodzaj obligacji', { exact: true }).selectOption('TOS')
  await expect(bonds.getByLabel('Marża ponad inflację (%) — opcjonalnie', { exact: true })).toHaveCount(0)
  expect(await page.locator('form form').count()).toBe(0)
  await kind.selectOption('ETF')
  await expect(section.getByLabel('Nazwa instrumentu', { exact: true })).toHaveValue('TEST szkic ETF')
  await expect(section.getByLabel('Ticker instrumentu', { exact: true })).toBeVisible()
  await expect(section.getByRole('region', { name: 'Obligacje skarbowe', exact: true })).toHaveCount(0)
})
