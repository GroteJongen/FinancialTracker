import { test, expect } from './fixtures'

test('custom portfolio groups mixed assets, filters IKE and shows the six requested columns', async ({ page }) => {
  const tag = Date.now().toString()
  const standard = await (await page.request.post('/api/investment-accounts', { data: { name: 'TEST group standard ' + tag, kind: 'STANDARD', currency: 'PLN' } })).json()
  const ike = await (await page.request.post('/api/investment-accounts', { data: { name: 'TEST group IKE ' + tag, kind: 'IKE', currency: 'PLN' } })).json()
  const stock = await (await page.request.post('/api/securities', { data: { kind: 'ETF', name: 'TEST World ETF ' + tag, symbol: 'W' + tag, mic: 'XETR', currency: 'PLN' } })).json()
  const reit = await (await page.request.post('/api/securities', { data: { kind: 'REIT', name: 'TEST REIT ' + tag, symbol: 'R' + tag, mic: 'XNYS', currency: 'PLN' } })).json()
  for (const [account, listing, price] of [[standard, stock, '110'], [ike, reit, '90']]) {
    await page.request.post(`/api/accounts/${account.id}/purchases`, { data: { listing_id: listing.id, request_id: crypto.randomUUID(), trade_date: '2026-11-01', quantity: '10', unit_price: '100', commission: '0', currency: 'PLN' } })
    await page.request.post(`/api/accounts/${account.id}/prices`, { data: { listing_id: listing.id, request_id: crypto.randomUUID(), observed_on: '2026-11-20', price, currency: 'PLN' } })
  }
  await page.goto('/')
  const portfolio = page.locator('.portfolio-section')
  await expect(page.locator('.operations-panel')).not.toHaveAttribute('open', '')
  await portfolio.getByRole('button', { name: 'Nowy portfel', exact: true }).click()
  const form = portfolio.getByRole('form', { name: 'Nowy portfel', exact: true })
  await form.getByLabel('Nazwa portfela').fill('TEST long term ' + tag)
  await form.getByRole('checkbox', { name: new RegExp(standard.name) }).check()
  await form.getByRole('checkbox', { name: new RegExp(ike.name) }).check()
  await form.getByRole('button', { name: 'Zapisz portfel', exact: true }).click()
  await expect(form).toHaveCount(0)
  const table = portfolio.getByRole('table', { name: 'Wszystkie aktywa wybranego portfela' })
  await expect(table.getByRole('columnheader')).toHaveText(['Liczba jednostek', 'Nazwa', 'Cena jednostki', 'Wartość', 'Zysk / strata', 'Zysk / strata (%)'])
  await expect(table.getByRole('row')).toHaveCount(3)
  const etfRow = table.getByRole('row').filter({ hasText: stock.name })
  await expect(etfRow).toContainText('110,00 PLN')
  await expect(etfRow).toContainText('10,00%')
  await expect(table.getByRole('row').filter({ hasText: reit.name })).toContainText('-10,00%')
  await expect(portfolio.locator('.portfolio-cards')).toContainText('2\u00a0000,00 PLN')
  await portfolio.getByRole('group', { name: 'Filtr portfela' }).getByRole('button', { name: 'IKE', exact: true }).click()
  await expect(table.getByRole('row')).toHaveCount(2)
  await expect(table).toContainText(reit.name)
  await expect(table).not.toContainText(stock.name)
  await portfolio.getByRole('group', { name: 'Filtr portfela' }).getByRole('button', { name: 'Wszystkie', exact: true }).click()
  await table.getByRole('button', { name: stock.name, exact: true }).click()
  await expect(page.locator('.operations-panel')).toHaveAttribute('open', '')
  await expect(page.getByLabel('Wybierz instrument', { exact: true })).toHaveValue(stock.id)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})

test('generic catalogue can register a second ETF and a listed REIT without an IUSQ-specific view', async ({ page }) => {
  await page.goto('/')
  await page.locator('.operations-panel > summary').click()
  const section = page.getByRole('region', { name: 'Instrumenty giełdowe', exact: true })
  for (const kind of ['ETF', 'REIT']) {
    const tag = Date.now().toString()
    await section.getByRole('button', { name: 'Dodaj instrument', exact: true }).click()
    await section.getByLabel('Rodzaj aktywa', { exact: true }).selectOption(kind)
    await section.getByLabel('Nazwa instrumentu', { exact: true }).fill('TEST generic ' + kind + ' ' + tag)
    await section.getByLabel('Ticker instrumentu', { exact: true }).fill('G' + tag)
    await section.getByLabel('Giełda instrumentu (MIC)', { exact: true }).fill('XETR')
    await section.getByLabel('Waluta notowania instrumentu', { exact: true }).selectOption('EUR')
    await section.getByRole('button', { name: 'Zapisz instrument', exact: true }).click()
    await expect(section.getByLabel('Wybierz instrument', { exact: true }).locator('option:checked')).toContainText('TEST generic ' + kind)
  }
  await expect(page.getByRole('heading', { name: 'Zakupy IUSQ', exact: true })).toHaveCount(0)
})
